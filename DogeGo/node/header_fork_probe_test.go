package node

import (
	"path/filepath"
	"testing"

	"dogego/chain"
	"dogego/pow"
	"dogego/store"
)

func TestEncodeForkProbeGetHeaders(t *testing.T) {
	dir := t.TempDir()
	p, err := chain.ParamsFor(chain.RebootTestnet)
	if err != nil {
		t.Fatal(err)
	}
	g80, err := pow.Header80FromParams(p)
	if err != nil {
		t.Fatal(err)
	}
	j, err := store.OpenHeaderJournal(filepath.Join(dir, "h.bin"), g80[:])
	if err != nil {
		t.Fatal(err)
	}
	pl, err := encodeForkProbeGetHeaders(j, 0, p)
	if err != nil || len(pl) < 36 {
		t.Fatalf("payload len=%d err=%v", len(pl), err)
	}
}
