//go:build windows

package node

import (
	"syscall"
	"unsafe"
)

// MEMORYSTATUSEX layout for GlobalMemoryStatusEx (kernel32).
type memoryStatusEx struct {
	Length               uint32
	MemoryLoad           uint32
	TotalPhys            uint64
	AvailPhys            uint64
	TotalPageFile        uint64
	AvailPageFile        uint64
	TotalVirtual         uint64
	AvailVirtual         uint64
	AvailExtendedVirtual uint64
}

var (
	modkernel32              = syscall.NewLazyDLL("kernel32.dll")
	procGlobalMemoryStatusEx = modkernel32.NewProc("GlobalMemoryStatusEx")
)

// systemFreeMemoryMB returns currently available physical RAM in megabytes, or -1 on failure.
func systemFreeMemoryMB() int64 {
	var ms memoryStatusEx
	ms.Length = uint32(unsafe.Sizeof(ms))
	r1, _, _ := procGlobalMemoryStatusEx.Call(uintptr(unsafe.Pointer(&ms)))
	if r1 == 0 {
		return -1
	}
	return int64(ms.AvailPhys / (1024 * 1024))
}
