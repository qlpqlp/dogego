package node

import (
	"context"
	"errors"
	"strings"
)

// IsBenignShutdownErr reports context cancellation from graceful node stop (not a sync failure).
func IsBenignShutdownErr(err error) bool {
	if err == nil {
		return false
	}
	if errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) {
		return true
	}
	msg := strings.ToLower(err.Error())
	return strings.Contains(msg, "context canceled") || strings.Contains(msg, "context cancelled")
}
